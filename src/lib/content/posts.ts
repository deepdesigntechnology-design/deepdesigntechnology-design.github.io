export function getPost(slug: string) {
  return posts.find((p) => p.slug === slug);
}

export function postsByCategory(slug: CategorySlug) {
  return posts.filter((p) => p.category === slug);
}

export function categoryLabel(slug: CategorySlug) {
  return categories.find((c) => c.slug === slug)?.label ?? slug;
}

export function readingMinutes(post: Post) {
  const chars = post.sections
    .flatMap((s) => [
      s.heading ?? "",
      ...(s.paragraphs ?? []),
      ...(s.list ?? []),
      s.quote ?? "",
      s.warn ?? "",
    ])
    .join("").length;
  return Math.max(3, Math.round(chars / 900));
}
